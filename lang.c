static int current = LANG_VI;

void langSet(int lang) { current = (lang == LANG_EN) ? LANG_EN : LANG_VI; }
int langGet(void) { return current; }

const char *trIn(int lang, StrId id) {
    if ((int)id < 0 || id >= S_COUNT) return "";
    const char *s = (lang == LANG_EN ? EN : VI)[id];
    return s ? s : "";                     /* thieu ban dich: in chuoi rong (test_logic se bao loi) */
}

const char *tr(StrId id) { return trIn(current, id); }

const char *langCode(int lang) { return lang == LANG_EN ? "en" : "vi"; }

int langFromCode(const char *code) {
    return (code && strcmp(code, "en") == 0) ? LANG_EN : LANG_VI;
}
